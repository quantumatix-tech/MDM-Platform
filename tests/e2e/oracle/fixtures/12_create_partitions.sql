CREATE TABLE E2E_PARTITIONED_EVENT (
    EVENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    EVENT_DATE DATE NOT NULL,
    AMOUNT NUMBER(20,5),
    STATUS VARCHAR2(50) DEFAULT 'pending' NOT NULL,
    CONSTRAINT E2E_PARTITIONED_EVENT_PK PRIMARY KEY (EVENT_ID, EVENT_DATE)
)
PARTITION BY RANGE (EVENT_DATE) (
    PARTITION E2E_EVENT_2024 VALUES LESS THAN (DATE '2025-01-01'),
    PARTITION E2E_EVENT_2025_H1 VALUES LESS THAN (DATE '2025-07-01'),
    PARTITION E2E_EVENT_2025_H2 VALUES LESS THAN (DATE '2026-01-01'),
    PARTITION E2E_EVENT_MAX VALUES LESS THAN (MAXVALUE)
);
