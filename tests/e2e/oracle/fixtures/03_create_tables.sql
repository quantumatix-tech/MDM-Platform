CREATE TABLE E2E_CUSTOMER (
    CUSTOMER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CUSTOMER_CODE VARCHAR2(50) NOT NULL,
    DISPLAY_NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(150) NOT NULL,
    PHONE VARCHAR2(20),
    CITY VARCHAR2(100),
    STATUS VARCHAR2(20) DEFAULT 'active' NOT NULL,
    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_ON DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT E2E_CUSTOMER_PK PRIMARY KEY (CUSTOMER_ID),
    CONSTRAINT E2E_CUSTOMER_UQ UNIQUE (CUSTOMER_CODE),
    CONSTRAINT E2E_CUSTOMER_EMAIL_UQ UNIQUE (EMAIL),
    CONSTRAINT E2E_CUSTOMER_CK CHECK (LENGTH(TRIM(DISPLAY_NAME)) > 0),
    CONSTRAINT E2E_CUSTOMER_EMAIL_CK CHECK (LENGTH(TRIM(EMAIL)) > 0),
    CONSTRAINT E2E_CUSTOMER_ACTIVE_CK CHECK (IS_ACTIVE IN (0, 1))
);

CREATE TABLE E2E_PRODUCT (
    PRODUCT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    SKU VARCHAR2(50) NOT NULL,
    NAME VARCHAR2(200) NOT NULL,
    CATEGORY VARCHAR2(100) DEFAULT 'General' NOT NULL,
    PRICE NUMBER(10,2) NOT NULL,
    STOCK_QTY NUMBER(10,0) DEFAULT 0 NOT NULL,
    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_ON DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT E2E_PRODUCT_PK PRIMARY KEY (PRODUCT_ID),
    CONSTRAINT E2E_PRODUCT_SKU_UQ UNIQUE (SKU),
    CONSTRAINT E2E_PRODUCT_PRICE_CK CHECK (PRICE >= 0),
    CONSTRAINT E2E_PRODUCT_STOCK_CK CHECK (STOCK_QTY >= 0),
    CONSTRAINT E2E_PRODUCT_ACTIVE_CK CHECK (IS_ACTIVE IN (0, 1))
);

CREATE TABLE E2E_ORDER (
    ORDER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CUSTOMER_ID NUMBER NOT NULL,
    ORDER_NUMBER NUMBER(20,0) NOT NULL,
    TOTAL_AMOUNT NUMBER(20,5),
    ORDER_STATUS VARCHAR2(20) DEFAULT 'pending' NOT NULL,
    ORDER_DATE TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    OBJECT_VALUE E2E_VALUE_T,
    ARRAY_VALUE E2E_VALUE_ARRAY_T,
    NOTES CLOB,
    RAW_DATA BLOB,
    CONSTRAINT E2E_ORDER_PK PRIMARY KEY (ORDER_ID),
    CONSTRAINT E2E_ORDER_UQ UNIQUE (ORDER_NUMBER),
    CONSTRAINT E2E_ORDER_CK CHECK (TOTAL_AMOUNT IS NULL OR TOTAL_AMOUNT >= 0),
    CONSTRAINT E2E_ORDER_STATUS_CK CHECK (
        ORDER_STATUS IN ('pending', 'processing', 'shipped', 'delivered', 'cancelled')
    )
);

CREATE TABLE E2E_ORDER_DETAIL (
    DETAIL_ID NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ORDER_ID NUMBER NOT NULL,
    PRODUCT_ID NUMBER NOT NULL,
    QUANTITY NUMBER(10,0) NOT NULL,
    UNIT_PRICE NUMBER(20,5) NOT NULL,
    LINE_TOTAL NUMBER(30,5) GENERATED ALWAYS AS (QUANTITY * UNIT_PRICE) VIRTUAL,
    CONSTRAINT E2E_ORDER_DETAIL_PK PRIMARY KEY (DETAIL_ID),
    CONSTRAINT E2E_ORDER_DETAIL_CK CHECK (QUANTITY > 0 AND UNIT_PRICE >= 0)
);

CREATE TABLE E2E_ORDER_AUDIT (
    AUDIT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ORDER_ID NUMBER NOT NULL,
    ACTION_NAME VARCHAR2(24) NOT NULL,
    ACTION_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT E2E_ORDER_AUDIT_PK PRIMARY KEY (AUDIT_ID)
);

CREATE TABLE E2E_PK_NAME_TEST (
    TEST_ID NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    TEST_NAME VARCHAR2(100) NOT NULL,
    CONSTRAINT E2E_PK_TEST_PRIMARY_KEY PRIMARY KEY (TEST_ID)
);
