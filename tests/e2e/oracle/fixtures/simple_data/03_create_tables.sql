CREATE TABLE SIMPLE_CUSTOMER (
    CUSTOMER_ID NUMBER(10) NOT NULL,
    CUSTOMER_NAME VARCHAR2(80) NOT NULL,
    CREDIT_LIMIT NUMBER(14,2),
    CONSTRAINT SIMPLE_CUSTOMER_PK PRIMARY KEY (CUSTOMER_ID)
);

CREATE TABLE SIMPLE_ORDER (
    ORDER_ID NUMBER(10) NOT NULL,
    CUSTOMER_ID NUMBER(10) NOT NULL,
    ORDER_TOTAL NUMBER(18,4) NOT NULL,
    ORDER_DATE DATE NOT NULL,
    CONSTRAINT SIMPLE_ORDER_PK PRIMARY KEY (ORDER_ID)
);
