CREATE PROCEDURE E2E_RENAME_CUSTOMER (P_CUSTOMER_ID IN NUMBER, P_DISPLAY_NAME IN VARCHAR2) IS
BEGIN
    UPDATE E2E_CUSTOMER SET DISPLAY_NAME = P_DISPLAY_NAME
    WHERE CUSTOMER_ID = P_CUSTOMER_ID;
    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Customer not found');
    END IF;
END;
/
