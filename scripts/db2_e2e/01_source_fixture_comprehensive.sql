-- scripts/db2_e2e/01_source_fixture_comprehensive.sql
-- COMPREHENSIVE Db2 11.5.9 SOURCE FIXTURE FOR FRESH DATABASE
-- Run against NEW source database (E2ESRC02) as DB2ADMIN
-- Creates schema and ALL supported object types in dependency order
-- ALL top-level statements terminated with @ (use db2 -td@ -svf)

-- ============================================================
-- 1. SCHEMA
-- ============================================================
CREATE SCHEMA TESTE2E @

-- ============================================================
-- 2. DISTINCT UDTs (must exist before dependent tables)
-- ============================================================
CREATE DISTINCT TYPE TESTE2E.EMP_CODE AS INTEGER @
CREATE DISTINCT TYPE TESTE2E.REGION_CODE AS SMALLINT @

-- ============================================================
-- 3. SEQUENCES (standalone, before identity tables)
-- ============================================================
CREATE SEQUENCE TESTE2E.EMP_SEQ AS INTEGER START WITH 100 INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 CYCLE CACHE 20 ORDER @
CREATE SEQUENCE TESTE2E.ORDER_SEQ AS INTEGER START WITH 1000 INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 NO CYCLE CACHE 20 NO ORDER @

-- ============================================================
-- 4. ORDINARY TABLES (dependency order: parent before child)
-- ============================================================

-- Parent: Departments
CREATE TABLE TESTE2E.DEPARTMENTS (
  DEPT_ID INTEGER NOT NULL,
  DEPT_NAME VARCHAR(50) NOT NULL,
  MANAGER_ID INTEGER,
  PRIMARY KEY (DEPT_ID)
) @

-- Child: Employees (references DEPARTMENTS)
CREATE TABLE TESTE2E.EMPLOYEES (
  EMP_ID INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 NO CYCLE CACHE 20 NO ORDER),
  EMP_NAME VARCHAR(100) NOT NULL,
  DEPT_ID INTEGER,
  SALARY DECIMAL(10,2) DEFAULT 50000.00,
  EMP_CODE TESTE2E.EMP_CODE,
  HIRE_DATE DATE DEFAULT CURRENT DATE,
  PRIMARY KEY (EMP_ID),
  FOREIGN KEY (DEPT_ID) REFERENCES TESTE2E.DEPARTMENTS (DEPT_ID) ON DELETE SET NULL,
  CONSTRAINT CK_SALARY CHECK (SALARY >= 0)
) @

-- Parent: Regions
CREATE TABLE TESTE2E.REGIONS (
  REGION_ID INTEGER NOT NULL,
  REGION_NAME VARCHAR(50) NOT NULL,
  REGION_CODE TESTE2E.REGION_CODE,
  PRIMARY KEY (REGION_ID)
) @

-- Child: Orders (references REGIONS)
CREATE TABLE TESTE2E.ORDERS (
  ORDER_ID INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 NO CYCLE CACHE 20 NO ORDER),
  REGION_ID INTEGER NOT NULL,
  AMOUNT DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  ORDER_DATE DATE DEFAULT CURRENT DATE,
  PRIMARY KEY (ORDER_ID),
  FOREIGN KEY (REGION_ID) REFERENCES TESTE2E.REGIONS (REGION_ID) ON DELETE RESTRICT,
  CONSTRAINT CK_AMOUNT CHECK (AMOUNT >= 0)
) @

-- UDT column table
CREATE TABLE TESTE2E.EMP_UDT (
  ID INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 NO CYCLE CACHE 20 NO ORDER),
  CODE TESTE2E.EMP_CODE,
  PRIMARY KEY (ID)
) @

-- CHECK/DEFAULT table (no FK)
CREATE TABLE TESTE2E.RULES (
  ID INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 NO CYCLE CACHE 20 NO ORDER),
  SALARY DECIMAL(10,2) DEFAULT 1000.00,
  STATUS VARCHAR(10) DEFAULT 'ACTIVE',
  BONUS INTEGER DEFAULT 0,
  CONSTRAINT CK_SALARY CHECK (SALARY >= 0),
  CONSTRAINT CK_STATUS CHECK (STATUS IN ('ACTIVE','INACTIVE')),
  PRIMARY KEY (ID)
) @

-- Generated column table
CREATE TABLE TESTE2E.GEN (
  ID INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 NO CYCLE CACHE 20 NO ORDER),
  BASE_SALARY INTEGER NOT NULL,
  BONUS INTEGER NOT NULL,
  TOTAL_SALARY INTEGER GENERATED ALWAYS AS (BASE_SALARY + BONUS),
  TAX_RATE DECFLOAT(16),
  PRIMARY KEY (ID)
) @

-- ============================================================
-- 5. RANGE-PARTITIONED TABLE
-- ============================================================
CREATE TABLE TESTE2E.PARTITIONED_EMPS (
  EMP_ID INTEGER NOT NULL,
  EMP_NAME VARCHAR(100),
  SALARY INTEGER
) PARTITION BY RANGE (EMP_ID)
  (STARTING FROM (1) ENDING AT (100) INCLUSIVE,
   STARTING FROM (101) ENDING AT (200) INCLUSIVE,
   STARTING FROM (201) ENDING AT (300) INCLUSIVE) @

-- ============================================================
-- 6. AUDIT TABLE (for trigger)
-- ============================================================
CREATE TABLE TESTE2E.ORDER_AUDIT (
  ORDER_ID INTEGER,
  EVENT_TYPE VARCHAR(10),
  EVENT_TIME TIMESTAMP DEFAULT CURRENT TIMESTAMP
) @

-- ============================================================
-- 7. ALIASES
-- ============================================================
CREATE ALIAS TESTE2E.EMP_ALIAS FOR TESTE2E.EMPLOYEES @
CREATE ALIAS TESTE2E.DEPT_ALIAS FOR TESTE2E.DEPARTMENTS @

-- ============================================================
-- 8. VIEWS
-- ============================================================
CREATE VIEW TESTE2E.EMP_VIEW AS
SELECT EMP_ID, EMP_NAME, DEPT_ID, SALARY FROM TESTE2E.EMPLOYEES WHERE SALARY > 40000 @

CREATE VIEW TESTE2E.DEPT_SUMMARY AS
SELECT D.DEPT_ID, D.DEPT_NAME, COUNT(E.EMP_ID) AS EMP_COUNT
FROM TESTE2E.DEPARTMENTS D
LEFT JOIN TESTE2E.EMPLOYEES E ON D.DEPT_ID = E.DEPT_ID
GROUP BY D.DEPT_ID, D.DEPT_NAME @

-- ============================================================
-- 9. MQT (Materialized Query Table)
-- ============================================================
CREATE TABLE TESTE2E.EMP_MQT AS (
  SELECT DEPT_ID, COUNT(*) AS EMP_COUNT, AVG(SALARY) AS AVG_SALARY
  FROM TESTE2E.EMPLOYEES
  GROUP BY DEPT_ID
) DATA INITIALLY DEFERRED REFRESH DEFERRED @

-- ============================================================
-- 10. SQL FUNCTION
-- ============================================================
CREATE FUNCTION TESTE2E.FN_DOUBLE (X INTEGER)
RETURNS INTEGER
LANGUAGE SQL
RETURN X * 2 @

CREATE FUNCTION TESTE2E.FN_TAX (BASE DECIMAL(10,2), RATE DECFLOAT(16))
RETURNS DECIMAL(10,2)
LANGUAGE SQL
RETURN BASE * DECIMAL(RATE, 10, 4) @

-- ============================================================
-- 11. SQL PROCEDURE (compound SQL - internal semicolons preserved)
-- ============================================================
CREATE PROCEDURE TESTE2E.SP_EMP_COUNT (OUT P_COUNT INTEGER)
LANGUAGE SQL
BEGIN
  SELECT COUNT(*) INTO P_COUNT FROM TESTE2E.EMPLOYEES;
END @

CREATE PROCEDURE TESTE2E.SP_DEPT_STATS (IN P_DEPT_ID INTEGER, OUT P_AVG_SALARY DECIMAL(10,2), OUT P_MAX_SALARY DECIMAL(10,2))
LANGUAGE SQL
BEGIN
  DECLARE V_AVG DECIMAL(10,2);
  DECLARE V_MAX DECIMAL(10,2);
  SELECT AVG(SALARY), MAX(SALARY) INTO V_AVG, V_MAX FROM TESTE2E.EMPLOYEES WHERE DEPT_ID = P_DEPT_ID;
  SET P_AVG_SALARY = V_AVG;
  SET P_MAX_SALARY = V_MAX;
END @

-- ============================================================
-- 12. TRIGGER (compound SQL - internal semicolons preserved)
-- ============================================================
CREATE TRIGGER TESTE2E.TRG_ORDER_UPDATE
AFTER UPDATE OF AMOUNT ON TESTE2E.ORDERS
REFERENCING NEW AS N
FOR EACH ROW
BEGIN
  INSERT INTO TESTE2E.ORDER_AUDIT (ORDER_ID, EVENT_TYPE) VALUES (N.ORDER_ID, 'UPDATE');
END @

CREATE TRIGGER TESTE2E.TRG_EMP_INSERT
AFTER INSERT ON TESTE2E.EMPLOYEES
REFERENCING NEW AS N
FOR EACH ROW
BEGIN
  INSERT INTO TESTE2E.ORDER_AUDIT (ORDER_ID, EVENT_TYPE) VALUES (N.EMP_ID, 'EMP_INSERT');
END @

